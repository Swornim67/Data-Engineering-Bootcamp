-- 3) candidate key 
-- it is any column or a combination or group of columns that can uniquely identify the row.
-- A table can have multiple candidate key.
-- from those candidate key you can choose any one primary key .

select * from customer;	

-- from this customer we have unique things like
-- customer_id, email, phone number    these 3 things are called as candidate key.
-- from these columns we can choose any one of them to make them as primary key. 