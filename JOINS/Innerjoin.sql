-- INNER JOIN :- The most used join in the sql and the most common question to be asked in the interview.
-- So this inner join will just match the records from both the tables or common record between the table as per joining the key.



-- creating a new database for the joins_practice

create database joins_practice;
use joins_practice;

-- Not adding any foreign key.
-- creating tables:customer,orders,product,payment.

-- DDL FOR THE CUSTOMER TABLE
create table if not exists customer
(
customer_id int primary key,
customer_name varchar(50),
city varchar(50),
signup_date date
);

-- DDL FOR THE ORDERS TABLE.
create table if not exists orders
(
order_id int primary key,
customer_id int,
product_id int,
order_amount decimal(10,2),
order_date date,
order_status varchar(50)
);

-- DDL FOR THE PRODUCT TABLE
create table if not exists product
(
product_id int primary key,
product_name varchar(50) not null,
category varchar(50)
);

-- DDL FOR THE PAYEMENT TABLE.
create table if not exists payement
(
payment_id int primary key,
order_id int,
payment_mode varchar(50),
payment_status varchar(50),
paid_amount decimal(10,2),
payment_date date
);

