-- show the previous query but only for kathmandu only.
select o.order_id,
c.customer_name,
pro.product_name,
o.order_amount,
o.order_status,
pay.paid_amount,
pay.payment_status

from customer as c
inner join orders as o
on c.customer_id=o.customer_id
inner join product as pro
on o.product_id=pro.product_id 
inner join payment as pay
on o.order_id=pay.order_id
where c.city='Kathmandu';


-- Aggregation scenario
-- find the total revenue generated by each city

select 
c.city,
sum(pay.paid_amount) as `Total revenue`
from customer as c
inner join orders as o
on c.customer_id=o.customer_id
inner join payment as pay
on o.order_id=pay.order_id
group by c.city;
