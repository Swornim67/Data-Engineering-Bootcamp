-- show the orders details with the customer name and product name

select o.order_id,
c.customer_name,
c.city,
o.order_amount,
o.order_date,
o.order_status,
p.product_name
from customer as c
inner join orders as o 
on c.customer_id=o.customer_id
inner join product as p
on p.product_id=o.product_id;


-- show the customer_name,customer_details,order_details,payment_mode and product details 
